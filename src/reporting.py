"""Render validation and baseline reports from computed results only.

Every table in the emitted markdown is derived from a DataFrame produced by an
actual run. There are no placeholder numbers: when a stage did not run, the
report says so in words rather than showing a value.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from src.validation import (
    BLOCKED_WELL_IDS,
    PROTOCOL_A,
    PROTOCOL_B,
    PROTOCOL_INVALID,
)


def _md_table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    if df is None or df.empty:
        return "_no rows_\n"
    out = df.copy()
    for c in out.columns:
        if pd.api.types.is_float_dtype(out[c]):
            out[c] = out[c].map(lambda v: "" if pd.isna(v) else floatfmt.format(v))
        else:
            out[c] = out[c].astype(str)
    header = "| " + " | ".join(out.columns) + " |"
    rule = "|" + "|".join("---" for _ in out.columns) + "|"
    rows = ["| " + " | ".join(r) + " |" for r in out.to_numpy()]
    return "\n".join([header, rule, *rows]) + "\n"


def spatial_ablation(summary: pd.DataFrame) -> pd.DataFrame:
    """Pair each `<model>` with `<model>_spatial` and report the delta."""
    gk = summary[summary["protocol"] == "groupkfold"]
    rows = []
    for _, base in gk[~gk["model"].str.endswith("_spatial")].iterrows():
        sp = gk[gk["model"] == f"{base['model']}_spatial"]
        if sp.empty:
            continue
        sp = sp.iloc[0]
        rows.append(
            {
                "model": base["model"],
                "global_rmse_without_spatial": base["global_rmse"],
                "global_rmse_with_spatial": sp["global_rmse"],
                "delta_global_rmse": sp["global_rmse"] - base["global_rmse"],
                "pct_change": 100.0
                * (sp["global_rmse"] - base["global_rmse"])
                / base["global_rmse"]
                if base["global_rmse"]
                else np.nan,
                "median_well_rmse_without_spatial": base["median_well_rmse"],
                "median_well_rmse_with_spatial": sp["median_well_rmse"],
                "worst10_without_spatial": base["worst10_well_rmse"],
                "worst10_with_spatial": sp["worst10_well_rmse"],
                "verdict": "spatial helps"
                if sp["global_rmse"] < base["global_rmse"]
                else "spatial does not help",
            }
        )
    return pd.DataFrame(rows)


SYNTHETIC_BANNER = """> # ⚠️ SYNTHETIC PIPELINE VERIFICATION ONLY
>
> **These numbers are NOT competition validation results.** They were produced
> from a synthetic field generated by `scripts/make_synthetic_field.py`, not
> from the ROGII Kaggle data. They exist to prove that the harness executes
> correctly — folds are clean, guards fire, models run and rank — and for
> nothing else.
>
> The synthetic generator constructs TVT as `surface − Z`, which hands the
> geometric baseline a near-exact relationship it will not enjoy on real data.
> **Do not quote any figure below as a real result.** Real metrics require
> `scripts/run_validation.py` on the mounted Kaggle competition data.
"""


def write_baseline_report(
    path,
    *,
    results: pd.DataFrame,
    well_df: pd.DataFrame,
    strat: pd.DataFrame,
    env: dict,
    folds: pd.DataFrame,
    spatial_df: pd.DataFrame,
    failures: pd.DataFrame,
) -> Path:
    p = Path(path)
    is_synth = "SYNTHETIC" in str(env.get("label", "")).upper()

    unseen = results[results["protocol"] == PROTOCOL_B].sort_values("global_rmse")
    masked = results[results["protocol"] == PROTOCOL_A].sort_values("global_rmse")
    invalid = results[results["protocol"] == PROTOCOL_INVALID].sort_values("global_rmse")

    # Model selection uses Protocol B only, and never the invalid diagnostic.
    primary = unseen if len(unseen) else masked
    best = primary.iloc[0] if len(primary) else None

    lines: list[str] = []
    A = lines.append
    A("# Baseline Report\n")
    if is_synth:
        A(SYNTHETIC_BANNER)
    A(f"Generated {env['timestamp_utc']} · runtime {env['runtime_seconds']:.1f}s · "
      f"peak RSS {env['peak_rss_mb']:.0f} MB\n")
    A(f"Wells validated: **{env['n_wells_validated']}** of "
      f"{env['n_train_wells_discovered']} train wells "
      f"({env['n_folds']}-fold GroupKFold, seed {env['seed']}). "
      f"Points evaluated per model: **{env['n_points_evaluated']:,}**. "
      f"Failures: **{env['n_failures']}**.\n")
    A("**Every protocol below is cross-fitted by well ID: no model is fitted "
      "on a well it is scored on.**\n")
    A(f"Public test wells excluded from every fit, fold and tuning step: "
      f"`{'`, `'.join(env['blocked_well_ids'])}`.\n")
    if not env.get("lightgbm_available", True):
        A("> **LightGBM was not installed in this environment.** It is recorded "
          "as unavailable; no substitute model was scored in its place.\n")

    A("\n## 1. Headline\n")
    if best is not None:
        proto_name = ("unseen-well GroupKFold (Protocol B)" if len(unseen)
                      else "same-well masked suffix (Protocol A)")
        A(f"**Best baseline: `{best['model']}`** on {proto_name}.\n")
        A(f"- Global point-level RMSE: **{best['global_rmse']:.3f}**")
        A(f"- Mean well RMSE: {best['mean_well_rmse']:.3f}")
        A(f"- Median well RMSE: **{best['median_well_rmse']:.3f}**")
        A(f"- Worst-10-well RMSE: {best['worst10_well_rmse']:.3f}")
        A(f"- Worst single well: {best['worst_well_rmse']:.3f} "
          f"(`{best['worst_well_id']}`)")
        A(f"- Max absolute point error: {best['max_abs_error']:.3f}")
        A(f"- Mean bias: {best['mean_bias']:+.3f}")
        A(f"- Wells evaluated: {int(best['n_wells'])} · "
          f"points evaluated: {int(best['n_points']):,}\n")

    A("\n## 2. Protocol B — unseen-well GroupKFold\n")
    A("Models are fitted on fold-train wells and scored on the **real hidden "
      "suffix** of fold-validation wells, against the `TVT` label. The model "
      "has never seen the well it is scored on. This is the protocol that "
      "resembles the leaderboard, and the only one used to rank models.\n")
    A(_md_table(unseen.drop(columns=["protocol"]) if len(unseen) else unseen))

    A("\n## 3. Protocol A — same-well masked suffix\n")
    A("The prediction boundary is simulated earlier, inside the visible prefix, "
      "so the truth comes from `TVT_input` and the `TVT` label column is never "
      "read. **Also cross-fitted by well ID** — the well supplies the task, not "
      "the training data. Measures continuation skill.\n")
    A(_md_table(masked.drop(columns=["protocol"]) if len(masked) else masked))

    if len(invalid):
        A("\n### 3b. In-sample diagnostic — INVALID, shown for contrast only\n")
        A("Fitted and scored on the **same** wells. This is not a validation "
          "result; it is included to quantify how large the in-sample illusion "
          "is. The gap between these figures and Protocol B is memorisation "
          "that a naive harness would have reported as skill.\n")
        A(_md_table(invalid.drop(columns=["protocol"])))
        if len(unseen):
            merged = invalid.merge(
                unseen, on="model", suffixes=("_insample", "_unseen")
            )
            if len(merged):
                gap = merged[["model", "global_rmse_insample", "global_rmse_unseen"]].copy()
                gap["optimism_factor"] = (
                    gap["global_rmse_unseen"] / gap["global_rmse_insample"].replace(0, np.nan)
                )
                A("\nOptimism of the in-sample number "
                  "(how many times worse the honest result is):\n")
                A(_md_table(gap.sort_values("optimism_factor", ascending=False)))

    valid_strat = (
        strat[strat["protocol"] != PROTOCOL_INVALID] if len(strat) else strat
    )

    A("\n## 4. RMSE by hidden suffix length\n")
    A("Error growth with extrapolation distance. Geometry extrapolates; only "
      "the GR family ingests new information inside the hidden region.\n")
    s1 = valid_strat[valid_strat["stratify_by"] == "hidden_suffix_length"] if len(valid_strat) else valid_strat
    A(_md_table(s1.drop(columns=["stratify_by"]) if len(s1) else s1))

    A("\n## 5. RMSE by GR missingness\n")
    A("The audit found 145 wells with high GR missingness (worst 80.1%). A "
      "model that is excellent on clean wells and catastrophic here is not "
      "deployable.\n")
    s2 = valid_strat[valid_strat["stratify_by"] == "gr_missingness"] if len(valid_strat) else valid_strat
    A(_md_table(s2.drop(columns=["stratify_by"]) if len(s2) else s2))

    A("\n## 6. RMSE by prefix length\n")
    A("Short prefixes give a poorly determined anchor and slope.\n")
    s3 = valid_strat[valid_strat["stratify_by"] == "prefix_length"] if len(valid_strat) else valid_strat
    A(_md_table(s3.drop(columns=["stratify_by"]) if len(s3) else s3))

    A("\n## 7. Spatial (offset-well) features\n")
    if spatial_df is None or spatial_df.empty:
        A("Not run in this pass (`--spatial` not supplied). No spatial numbers "
          "are reported.\n")
    else:
        ab = spatial_ablation(results)
        A("Donors are fold-train wells only, rebuilt inside every fold. No "
          "validation well may donate (`assert_disjoint`), and the queried "
          "well's own samples are always excluded by ID, so the feature is "
          "leave-one-well-out for training and validation rows alike. See "
          "`validation_protocol.md` §5 for the exact construction and "
          "`spatial_construction.csv` for the per-fold donor counts.\n")
        A(_md_table(ab))

    A("\n## 8. Worst wells\n")
    if len(well_df):
        gkw = well_df[well_df["protocol"] == PROTOCOL_B]
        src = gkw if len(gkw) else well_df[well_df["protocol"] == PROTOCOL_A]
        if not len(src):
            src = well_df
        if best is not None:
            src = src[src["model"] == best["model"]]
        worst = src.nlargest(min(10, len(src)), "rmse")[
            ["well_id", "rmse", "max_abs_error", "bias", "suffix_len",
             "prefix_len", "gr_missing_frac", "has_typewell"]
        ]
        A(f"Ten worst wells for `{best['model'] if best is not None else 'n/a'}`:\n")
        A(_md_table(worst))

    A("\n## 9. Runtime and memory\n")
    A(f"- Total wall clock: **{env['runtime_seconds']:.1f}s**")
    A(f"- Peak resident memory: **{env['peak_rss_mb']:.0f} MB**")
    A(f"- Platform: {env['platform']}, {env['cpu_count']} CPU(s), "
      f"Python {env['python']}")
    A(f"- Wells skipped as unusable: {env['n_wells_skipped']}")
    A(f"- Total failures (task + fit + predict): **{env['n_failures']}**")
    A(f"- Wells evaluated: {env['n_wells_validated']} · "
      f"points evaluated per model: {env['n_points_evaluated']:,}\n")
    if failures is not None and len(failures):
        A("\nFailure breakdown by stage:\n")
        A(_md_table(failures.groupby("stage").size().reset_index(name="count")))
        A("\nFirst failures:\n")
        A(_md_table(failures.head(10)))
    if len(folds):
        A("\nPer-fold timing:\n")
        A(_md_table(folds))
    if len(well_df):
        per_model = (
            well_df.groupby("model")["predict_seconds"]
            .agg(["sum", "mean"])
            .reset_index()
            .rename(columns={"sum": "predict_seconds_total", "mean": "predict_seconds_per_well"})
            .sort_values("predict_seconds_total", ascending=False)
        )
        A("\nInference cost per model:\n")
        A(_md_table(per_model, floatfmt="{:.4f}"))

    A("\n## 10. Leakage controls in force\n")
    A("| Control | Mechanism |")
    A("|---|---|")
    A("| TVT never a feature | Models receive `InferenceTask`, which has no target attribute |")
    A("| TVT_input never read past the boundary | NaN from `start` onward; `assert_no_target()` verifies |")
    A("| Train-only markers rejected | `assert_safe_features` raises on ANCC/ASTNL/ASTNU/BUDA/EGFDL/EGFDU |")
    A("| Unaudited columns rejected | The manifest is a whitelist, not a blacklist |")
    A("| Public test wells excluded | `assert_no_blocked_wells` at universe, fold, fit, donor and results |")
    A("| Wells never span folds | `GroupKFold` by well ID |")
    A("| No model fitted on a well it scores | Both protocols run through `run_cross_fitted_protocol`, which raises `CrossFitLeakage` on any train/validation overlap |")
    A("| In-sample results cannot be mistaken for validation | Diagnostic is named `INVALID_in_sample` and excluded from ranking and stratified tables |")
    A("| Spatial features fold-safe | Prior rebuilt per fold from fold-train donors; self excluded by ID |")
    A(f"\nBlocked IDs: `{'`, `'.join(sorted(BLOCKED_WELL_IDS))}` — "
      f"{env['blocked_wells_in_validation']} appeared in validation.\n")

    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(lines))
    return p


def write_validation_protocol(path, *, env: dict, folds: pd.DataFrame) -> Path:
    """Record the parameters of THIS run (the authored design doc is tracked)."""
    p = Path(path)
    is_synth = "SYNTHETIC" in str(env.get("label", "")).upper()
    banner = SYNTHETIC_BANNER + "\n" if is_synth else ""
    text = f"""# Validation Protocol — executed run

{banner}Generated {env['timestamp_utc']}. This file records what was actually
executed in the run that produced `validation_results.csv`. The authored design
document is `reports/validation_protocol.md`.

## Cross-fitting

`cross_fitted = {env['cross_fitted']}`

**Both** protocols route through `src.validation.run_cross_fitted_protocol`,
which fits on fold-train wells and scores on fold-validation wells. It raises
`CrossFitLeakage` if those sets intersect. No model is fitted on a well it is
scored on, in either protocol.

In-sample evaluation is invalid because a model with enough capacity
(LightGBM with hundreds of trees, say) can memorise a well's individual
trajectory. Scoring it on the same well then measures recall of the training
set, not the ability to predict an unseen suffix, and the resulting number is
arbitrarily good and completely uninformative about leaderboard performance.

## Protocols executed

{chr(10).join(f'- `{p}`' for p in env['protocols'])}

| Protocol | Boundary | Truth source | Fitting |
|---|---|---|---|
| `{PROTOCOL_A}` | simulated, earlier inside the visible prefix | `TVT_input` — the `TVT` label is never read | fold-train wells only |
| `{PROTOCOL_B}` | the real competition Prediction Start | the `TVT` label on the real hidden suffix | fold-train wells only |

In-sample diagnostic run: **{env['in_sample_diagnostic']}**. When enabled its
rows carry the protocol name `{PROTOCOL_INVALID}` and are excluded from ranking,
stratified tables and model selection.

The two protocols are reported separately and are never averaged into a single
number: they answer different questions (continuation skill vs. generalisation
to a new well) and can fail independently.

## Parameters

| Field | Value |
|---|---|
| Folds | {env['n_folds']} (GroupKFold by well ID) |
| Seed | {env['seed']} |
| Models | {', '.join(env['models'])} |
| Spatial features | {env['spatial_enabled']} |
| Train wells discovered | {env['n_train_wells_discovered']} |
| Test wells discovered | {env['n_test_wells_discovered']} |
| Wells validated | {env['n_wells_validated']} |
| Points evaluated (per model) | {env['n_points_evaluated']:,} |
| Wells skipped | {env['n_wells_skipped']} |
| Failures | {env['n_failures']} |
| Runtime (s) | {env['runtime_seconds']:.1f} |
| Peak RSS (MB) | {env['peak_rss_mb']:.0f} |
| Python | {env['python']} |
| Platform | {env['platform']} |
| CPUs | {env['cpu_count']} |
| numpy / pandas | {env['numpy']} / {env['pandas']} |
| LightGBM available | {env['lightgbm_available']} |
| Train dir | `{env['train_dir']}` |
| Test dir | `{env['test_dir']}` |

## Public test well isolation

Blocked IDs: {', '.join(f'`{w}`' for w in env['blocked_well_ids'])}

Appearances in validation: **{env['blocked_wells_in_validation']}**

The guard `assert_no_blocked_wells` is applied at the universe, at every fold's
train and validation list, at model fitting, at spatial donor construction and
at the written results table. It has no disable flag.

## Per-fold execution

{_md_table(folds)}
"""
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
    return p
